#!/bin/bash

# Generate or reuse the private .env configuration for the QuakeStrikePH demo.
# Authors: Armenta, Buergo, Candelaria, Pispis
# Usage: sudo bash quakestrikeph-config.sh [--output /root/demo.env] [--directory /srv/quakestrikeph]
# AI assistance: GPT 6.2 Sol (Codex) and Gemini 4 Neon (Antigravity) assisted with edge-case checks, refactoring, and review (see inline notes).
# Settings adapted from QuakeStrikePH .env.example and docs/operations/local-runtime.md.

output_file="/root/demo.env"
app_directory="/srv/quakestrikeph"

fail()
{
    echo "Configuration setup failed: $*" >&2
    exit 1
}

while [ "$#" -gt 0 ]
do
    if [ "$1" = "--help" ]
    then
        echo "Usage: sudo bash quakestrikeph-config.sh [--output FILE] [--directory PATH]"
        echo "Generate a private root-only .env file for QuakeStrikePH, or reuse an existing one."
        echo ""
        echo "Options:"
        echo "  --output FILE     Private config file path. Default: /root/demo.env"
        echo "  --directory PATH  Application folder. Default: /srv/quakestrikeph"
        echo "  --help            Show this help message and exit."
        echo ""
        echo "Example:"
        echo "  sudo bash quakestrikeph-config.sh --output /root/demo.env"
        exit 0

    elif [ "$1" = "--output" ] || [ "$1" = "--directory" ]
    then
        if [ "$#" -lt 2 ] || [ -z "$2" ]
        then
            fail "$1 requires a value."
        fi
        if [ "$1" = "--output" ]
        then
            output_file="$2"
        else
            app_directory="${2%/}"
        fi
        shift 2

    else
        fail "unknown option '$1'. Use --help."
    fi
done

if [ "$EUID" -ne 0 ]
then
    fail "run this script with root privileges."
fi

for required_command in openssl dirname stat grep cmp cp chown chmod
do
    if ! command -v "$required_command" > /dev/null
    then
        fail "$required_command is required."
    fi
done

installed_config="$app_directory/.env"

# AI-assisted: validate mode (600/400) and byte-match against installed .env for repeat-safety.
if [ -f "$output_file" ]
then
    file_mode=$(stat -c '%a' "$output_file")
    if [ "$file_mode" != "600" ] && [ "$file_mode" != "400" ]
    then
        fail "$output_file must have permissions 600 or 400."
    fi
    if [ -f "$installed_config" ] && ! cmp -s "$output_file" "$installed_config"
    then
        fail "$output_file differs from the installed $installed_config."
    fi
    echo "Configuration ready: existing $output_file kept unchanged."
    exit 0
fi

output_parent=$(dirname "$output_file")
if [ ! -d "$output_parent" ]
then
    fail "parent directory does not exist: $output_parent"
fi

# AI-assisted: set umask 077 before creating files so secrets are never world-readable.
umask 077

# Case 2: Output is missing, but the app already has an installed .env. Reuse it.
if [ -f "$installed_config" ]
then
    cp "$installed_config" "$output_file" || fail "could not copy installed .env."
    chown root:root "$output_file" && chmod 600 "$output_file" || fail "could not protect $output_file."
    echo "Configuration ready: copied existing settings from $installed_config."
    exit 0
fi

# Case 3: Fresh setup. Generate four random passwords and write the .env file.
postgres_password=$(openssl rand -hex 32) || fail "could not generate POSTGRES_PASSWORD."
migration_password=$(openssl rand -hex 32) || fail "could not generate MIGRATION_DB_PASSWORD."
worker_password=$(openssl rand -hex 32) || fail "could not generate WORKER_DB_PASSWORD."
backend_password=$(openssl rand -hex 32) || fail "could not generate BACKEND_DB_PASSWORD."

cat > "$output_file" <<EOF
# Private local demo configuration generated by quakestrikeph-config.sh
POSTGRES_DB=quakestrike
POSTGRES_USER=quakestrike
POSTGRES_PASSWORD=$postgres_password
MIGRATION_DB_PASSWORD=$migration_password
WORKER_DB_PASSWORD=$worker_password
BACKEND_DB_PASSWORD=$backend_password
MIGRATION_DATABASE_URL=postgresql+psycopg://quakestrike_migration:$migration_password@postgres:5432/quakestrike
DATABASE_URL=postgresql+psycopg://quakestrike_worker:$worker_password@postgres:5432/quakestrike
BACKEND_DATABASE_URL=postgresql://quakestrike_backend:$backend_password@postgres:5432/quakestrike
REDIS_URL=redis://redis:6379/0
ACCOUNT_REDIS_URL=redis://redis:6379/0
BACKEND_IMAGE_TAG=local
WORKER_IMAGE_TAG=local
MODEL_RELEASE_ID=a7f2286b-13a2-4708-a04d-4139281a4e1f
MODEL_ARTIFACT_DIRECTORY=/app/model-artifacts
MODEL_ARTIFACT_HOST_DIRECTORY=../model-artifacts
PHIVOLCS_CATALOG_URL=https://earthquake.phivolcs.dost.gov.ph/earthquake-information
PUBLIC_BULLETIN_BASE_URL=http://127.0.0.1:4321
ALERT_RESOLUTION_ENABLED=false
ALERT_DELIVERY_ENABLED=false
EOF

if [ "$?" -ne 0 ]
then
    fail "could not write $output_file."
fi

chown root:root "$output_file" || fail "could not set ownership on $output_file."
chmod 600 "$output_file" || fail "could not set permissions on $output_file."

echo "Configuration ready: created $output_file (mode 600)."
exit 0
